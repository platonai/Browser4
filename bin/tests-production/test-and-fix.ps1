#!/usr/bin/env pwsh

# ═══════════════════════════════════════════════════════════════════
# CROSS-PLATFORM: This script must run on Linux, macOS, and Windows.
# ═══════════════════════════════════════════════════════════════════
<#
.SYNOPSIS
    Run test-production.ps1, then auto-fix failures via AI analysis.

.DESCRIPTION
    Two-phase workflow:
      1. Run the full acceptance test suite (test-production.ps1).
      2. Collect all ai-analysis.txt files generated by failing tests,
         consolidate them, and invoke the best available AI CLI (claude
         or copilot) to produce a fix plan.  Optionally apply the fixes
         automatically.

    Designed for CI and local "test → fix → retest" loops.

.PARAMETER WorkingDir
    Working directory for test-production.ps1 (forwarded as -WorkingDir).

.PARAMETER MultiScenariosIterations
    Number of multi-scenario iterations (forwarded, default: 1).

.PARAMETER TimeoutHours
    Overall timeout in hours for step 1 (default: 4).

.PARAMETER FixPrompt
    Additional instructions appended to the AI fix prompt.

.PARAMETER OutputDir
    Directory for the consolidated fix report (default: repo bin/tests-production/logs).

.PARAMETER DryRun
    Show what would happen without actually running the tests or AI.

.EXAMPLE
    .\test-and-fix.ps1

.EXAMPLE
    .\test-and-fix.ps1 -MultiScenariosIterations 3 -TimeoutHours 6

.EXAMPLE
    .\test-and-fix.ps1 -DryRun
#>

[CmdletBinding()]
param(
    [string] $WorkingDir = '',
    [int] $MultiScenariosIterations = 1,
    [int] $TimeoutHours = 4,
    [string] $FixPrompt = '',
    [string] $OutputDir = '',
    [switch] $DryRun
)

$ErrorActionPreference = 'Stop'
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path

# Force UTF-8 throughout
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$PSDefaultParameterValues['*:Encoding'] = 'utf8'

# ── Resolve test-production.ps1 ────────────────────────────────────
$TestProductionScript = Join-Path $ScriptDir '..\test-production.ps1'
if (-not (Test-Path $TestProductionScript)) {
    $repoRoot = Resolve-Path (Join-Path $ScriptDir '..\..')
    $TestProductionScript = Join-Path $repoRoot 'bin\test-production.ps1'
}
# Normalise for display
$TestProductionScript = (Resolve-Path $TestProductionScript).Path

# ── Resolve output directory ───────────────────────────────────────
if (-not $OutputDir) {
    $OutputDir = Join-Path $ScriptDir 'logs'
}
$null = New-Item -Path $OutputDir -ItemType Directory -Force -ErrorAction SilentlyContinue

$workflowStartTime = Get-Date
$stamp = $workflowStartTime.ToString('yyyyMMdd_HHmmss')
$WorkflowLogFile = Join-Path $OutputDir "test-and-fix_${stamp}.log"

# ── Resolve AI analyzer ────────────────────────────────────────────
function Get-BestAi {
    $bin = $null
    foreach ($name in @('claude', 'copilot')) {
        $cmd = Get-Command $name -CommandType Application -ErrorAction SilentlyContinue
        if ($cmd) { $bin = $name; break }
    }
    return $bin
}

$AiBin = Get-BestAi
if (-not $AiBin) {
    Write-Warning 'No AI CLI found on PATH (checked: claude, copilot). Will still run tests but skip fix phase.'
}

# ═══════════════════════════════════════════════════════════════════
# Phase 1 — Run acceptance tests
# ═══════════════════════════════════════════════════════════════════
$phase1Start = Get-Date

Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
Write-Host '  test-and-fix — Phase 1: Run test-production.ps1' -ForegroundColor Cyan
Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
Write-Host "  Script        : $TestProductionScript"
Write-Host "  Iterations    : $MultiScenariosIterations"
Write-Host "  Timeout       : ${TimeoutHours}h"
Write-Host "  Workflow log  : $WorkflowLogFile"
Write-Host "  AI available  : $(if ($AiBin) { $AiBin } else { 'none' })"
Write-Host "  Started       : $($phase1Start.ToString('yyyy-MM-dd HH:mm:ss'))"
Write-Host ''

if ($DryRun) {
    Write-Host '  [DRY RUN] Would execute:' -ForegroundColor Yellow
    Write-Host "    pwsh -NoProfile -NonInteractive -File `"$TestProductionScript`" -MultiScenariosIterations $MultiScenariosIterations"
    Write-Host ''
    Write-Host '  [DRY RUN] Would then search for ai-analysis.txt files under:' -ForegroundColor Yellow
    Write-Host "    $OutputDir"
    exit 0
}

# Build arguments for test-production.ps1
$tpArgs = @(
    '-NoProfile',
    '-NonInteractive',
    '-File', $TestProductionScript
)
if ($WorkingDir) {
    $tpArgs += @('-WorkingDir', $WorkingDir)
}
$tpArgs += @('-MultiScenariosIterations', $MultiScenariosIterations)

# Run test-production.ps1 and tee output to both console and log file
Write-Host "━━━ Running test-production.ps1 ━━━" -ForegroundColor Cyan
Write-Host ''

$phase1ExitCode = 0
try {
    $phase1Output = & pwsh @tpArgs 2>&1
    $phase1ExitCode = $LASTEXITCODE
    if ($null -eq $phase1ExitCode) { $phase1ExitCode = 0 }

    # Write output to log file
    ($phase1Output | Out-String) | Set-Content -LiteralPath $WorkflowLogFile -Encoding UTF8

    # Display output (already shown by the child process, but capture for reference)
} catch {
    Write-Error "Phase 1 failed: $_"
    $phase1ExitCode = 1
}

$phase1Elapsed = (Get-Date) - $phase1Start
Write-Host ''
Write-Host "━━━ test-production.ps1 finished ━━━" -ForegroundColor Cyan
Write-Host "  Exit code     : $phase1ExitCode"
Write-Host ("  Elapsed       : {0:hh\:mm\:ss}" -f $phase1Elapsed)
Write-Host ''

# ═══════════════════════════════════════════════════════════════════
# Phase 2 — Collect AI analyses and invoke fixer
# ═══════════════════════════════════════════════════════════════════
Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
Write-Host '  test-and-fix — Phase 2: Collect & fix failures' -ForegroundColor Cyan
Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan

# Find ai-analysis.txt files generated since the workflow started.
# Search in the logs directory tree.
$analysisFiles = @(Get-ChildItem -Path $OutputDir -Recurse -Filter 'ai-analysis.txt' `
    -ErrorAction SilentlyContinue `
    | Where-Object { $_.LastWriteTime -ge $workflowStartTime } `
    | Sort-Object LastWriteTime -Descending)

if ($analysisFiles.Count -eq 0) {
    Write-Host "  ℹ No ai-analysis.txt files found (all tests passed or no AI analysis generated)." -ForegroundColor Green
    Write-Host ''
    Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
    Write-Host "  ✅ WORKFLOW COMPLETE — no failures to fix" -ForegroundColor Green
    Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
    exit $(if ($phase1ExitCode -eq 0) { 0 } else { $phase1ExitCode })
}

Write-Host "  Found $($analysisFiles.Count) ai-analysis.txt file(s):" -ForegroundColor Yellow
foreach ($af in $analysisFiles) {
    Write-Host "    📄 $($af.FullName)" -ForegroundColor DarkGray
}
Write-Host ''

# Consolidate analyses into a single prompt
$consolidatedAnalysis = ''
foreach ($af in $analysisFiles) {
    $consolidatedAnalysis += "─── ANALYSIS: $($af.FullName) ───`n"
    try {
        $content = Get-Content -LiteralPath $af.FullName -Raw -Encoding UTF8 -ErrorAction Stop
        $consolidatedAnalysis += $content.Trim() + "`n`n"
    } catch {
        $consolidatedAnalysis += "(could not read file)`n`n"
    }
}

# Also collect failures.json files for richer context
$failureJsonFiles = @(Get-ChildItem -Path $OutputDir -Recurse -Filter 'failures.json' `
    -ErrorAction SilentlyContinue `
    | Where-Object { $_.LastWriteTime -ge $workflowStartTime } `
    | Sort-Object LastWriteTime -Descending)

if ($failureJsonFiles.Count -gt 0) {
    $consolidatedAnalysis += "─── FAILURE JSON SUMMARIES ───`n"
    foreach ($fj in $failureJsonFiles) {
        $consolidatedAnalysis += "`n--- $($fj.FullName) ---`n"
        try {
            $jsonContent = Get-Content -LiteralPath $fj.FullName -Raw -Encoding UTF8 -ErrorAction Stop
            $jsonObj = $jsonContent | ConvertFrom-Json
            $consolidatedAnalysis += "Test: $($jsonObj.testName)`n"
            $consolidatedAnalysis += "Passed: $($jsonObj.passed), Failed: $($jsonObj.failed)`n"
            foreach ($f in $jsonObj.failures) {
                $consolidatedAnalysis += "  FAIL: $($f.command) (exit=$($f.exitCode), log=$($f.logFile))`n"
            }
        } catch {
            $consolidatedAnalysis += "(could not parse: $_)$n"
        }
    }
    $consolidatedAnalysis += "`n"
}

if (-not $AiBin) {
    Write-Host '  ⚠ No AI CLI available — skipping fix phase.' -ForegroundColor Yellow
    Write-Host '  Consolidated analysis written to log file for manual review.' -ForegroundColor Yellow
    $consolidatedAnalysis | Set-Content -LiteralPath (Join-Path $OutputDir "consolidated-analysis_${stamp}.txt") -Encoding UTF8
    Write-Host ''
    Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
    Write-Host "  ⚠ WORKFLOW COMPLETE — manual fix required" -ForegroundColor Yellow
    Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
    exit $(if ($phase1ExitCode -eq 0) { 0 } else { 1 })
}

# Build additional instructions prefix (cannot use if/else inside @"@" here-string)
$additionalInstructions = ''
if ($FixPrompt) {
    $additionalInstructions = "ADDITIONAL INSTRUCTIONS:`n$FixPrompt`n`n"
}

# Build the fix prompt
$fixPrompt = @"
You are analysing test failures from the Browser4 CLI acceptance test suite
(test-production.ps1).  Below are AI-generated analyses of each failing test,
plus structured failure summaries (failures.json).

YOUR TASK:
1. Read ALL the analyses and failure summaries below.
2. Identify the ROOT CAUSES — group related failures together.
3. For each root cause, propose a SPECIFIC CODE FIX with file paths and
   line-number references.  Prefer fixes that match the surrounding code style.

IMPORTANT: Only propose fixes for issues that actually appear in the analyses.
Do NOT invent issues that aren't mentioned.  Be specific — "fix the encoding"
is not specific enough; "add -Encoding UTF8 to Get-Content on line 304 of
test-utils.psm1" is.

${additionalInstructions}─── CONSOLIDATED TEST FAILURE ANALYSIS ───
$consolidatedAnalysis
─── END OF ANALYSIS ───
"@

# Write the prompt to a file so the AI can read it via --add-dir
$promptFile = Join-Path $OutputDir "fix-prompt_${stamp}.txt"
$fixPrompt | Set-Content -LiteralPath $promptFile -Encoding UTF8

Write-Host "━━━ Invoking $AiBin to fix failures ━━━" -ForegroundColor Magenta
Write-Host "  Prompt file   : $promptFile"
Write-Host "  Prompt size   : $($fixPrompt.Length) chars"
Write-Host ''

$fixReportFile = Join-Path $OutputDir "fix-report_${stamp}.txt"

$phase2Start = Get-Date
try {
    # Use --add-dir to give the AI access to the logs directory
    $shortPrompt = "Please read the instructions in the file '$promptFile' and follow them exactly. Analyse every failure, identify root causes, and propose specific code fixes with file paths and line numbers. Save your complete fix report to '$fixReportFile'."

    Write-Host "  Sending analysis to $AiBin ..." -ForegroundColor DarkGray
    $result = & $AiBin -p $shortPrompt --add-dir $OutputDir 2>&1
    $phase2Elapsed = (Get-Date) - $phase2Start

    Write-Host ''
    Write-Host "━━━ AI Fix Report ━━━" -ForegroundColor Magenta
    Write-Host ($result | Out-String)
    Write-Host ''

    # Save the fix report
    ($result | Out-String) | Set-Content -LiteralPath $fixReportFile -Encoding UTF8
    Write-Host "  📄 Fix report saved to: $fixReportFile" -ForegroundColor Green
    Write-Host ("  Elapsed        : {0:hh\:mm\:ss}" -f $phase2Elapsed)
} catch {
    Write-Warning "AI invocation failed: $_"
    $consolidatedAnalysis | Set-Content -LiteralPath (Join-Path $OutputDir "consolidated-analysis_${stamp}.txt") -Encoding UTF8
}

# Clean up temp prompt file
Remove-Item $promptFile -Force -ErrorAction SilentlyContinue

# ── Final summary ──────────────────────────────────────────────────
$totalElapsed = (Get-Date) - $workflowStartTime
Write-Host ''
Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
Write-Host '  WORKFLOW COMPLETE' -ForegroundColor Cyan
Write-Host '══════════════════════════════════════════════════════' -ForegroundColor Cyan
Write-Host ("  Phase 1 (test)  : {0:hh\:mm\:ss}  (exit=$phase1ExitCode)" -f $phase1Elapsed)
Write-Host "  Phase 2 (fix)   : $(if ($AiBin) { 'completed' } else { 'skipped (no AI)' })"
Write-Host ("  Total elapsed   : {0:hh\:mm\:ss}" -f $totalElapsed)
Write-Host "  Workflow log    : $WorkflowLogFile"
Write-Host "  Fix report      : $fixReportFile"
Write-Host ''

exit $(if ($phase1ExitCode -eq 0) { 0 } else { 1 })
