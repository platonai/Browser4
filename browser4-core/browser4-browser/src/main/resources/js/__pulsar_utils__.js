/**
 * Select the first element and click it.
 *
 * @param  {number} n The n-th anchor.
 * @param  {string|null} rootSelector The n-th anchor.
 * @return {string|null}
 */
__pulsar_utils__.clickNthAnchor = function(n, rootSelector) {
    let rootNode
    if (!rootSelector) {
        rootNode = document.body
    } else {
        rootNode = document.querySelector(rootSelector)
    }

    if (!rootNode) {
        return null
    }

    let c = 0
    let href = null

    __pulsar_TreeWalker.forEachElement(rootNode, function (node) {
        if (NodeOps.isAnchor(node) && NodeOps.maybeClickable(node)) {
            ++c;
            if (c === n) {
                node.scrollIntoView()
                href = node.getAttribute("href")
                node.click()
            }
        }
    });

    return href
}

