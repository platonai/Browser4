/**
 * Check if the document is fully loaded and ready to analyze.
 * A document is hardly be perfect ready in time, since it's very common there are very slow sub resources to wait for.
 * */
__pulsar_utils__.isActuallyReady = function() {
    // unexpected
    if (!document.body) {
        return false
    }

    this.__updateStat();

    if (!__pulsar_utils__.data) {
        return false
    }

    let ready = false;
    let trace = __pulsar_utils__.data.trace;
    let status = trace.status;
    let d = trace.lastD;

    // all sub resources are loaded, the document is ready now
    if (status.st === "c") {
        // assert(document.readyState === "complete")
        status.r = "st";
        ready = true
    }

    // The DOM is very good for analysis, no wait for more information
    let stat = trace.lastStat;
    if (status.n > 20 && stat.h >= this.fineHeight
        && stat.na >= this.fineNumAnchor
        && stat.ni >= this.fineNumImage
    ) {
        if (d.h < 10 && d.na === 0 && d.ni === 0 && d.nst === 0 && d.nnm === 0) {
            // DOM changed since last check, store the latest stat and return false to wait for the next check
            ++status.idl;
            if (status.idl > 10) {
                // idle for 10 seconds
                status.r = "ct";
                ready = true;
            }
        }
    }

    return ready;
};

__pulsar_utils__.isIdle = function() {
    let idle = false;
    let trace = __pulsar_utils__.data.trace;
    let status = trace.status;
    let d = trace.lastD;
    if (d.h < 10 && d.na === 0 && d.ni === 0 && d.nst === 0 && d.nnm === 0) {
        // DOM changed since last check, store the latest stat and return false to wait for the next check
        ++status.idl;
        if (status.idl > 5) {
            // idle for 5 seconds
            idle = true;
        }
    }
    return idle
};

/**
 * @return {Object}
 * */
__pulsar_utils__.__updateStat = function(init = false) {
    if (!document.body) {
        return
    }

    const config = this.getConfig();
    const viewPortWidth = config.viewPortWidth;

    // Width/height need to reflect the full page, but also must be robust:
    // some pages can report pathological sizes (infinite/huge due to bad CSS/JS).
    // We cap sizes to keep stats stable and avoid downstream overflows.
    const maxWidth = Math.max(1, 1.2 * viewPortWidth);
    const maxHeight = 150000; // 150k px is far beyond typical pages but prevents runaway values

    let width = 0;
    let height = 0;
    let na = 0;  // anchor
    let ni = 0;  // image
    let nst = 0; // short text in first screen
    let nnm = 0; // number like text in first screen

    if (!this.isBrowserError()) {
        NodeOps.forEach(document.body, (node) => {
            // 2023.08: google sites complains that node.__pulsar_isIFrame is not defined sometimes
            // We only want to skip iframe subtrees.
            if (NodeOps.isIFrame(node)) {
                return;
            }

            if (NodeOps.isAnchor(node)) ++na;
            if (NodeOps.isImage(node) && !NodeOps.isSmallImage(node)) ++ni;

            if (NodeOps.isText(node) && NodeOps.nScreen(node) <= 20) {
                let isShortText = NodeOps.isShortText(node);
                let isNumberLike = isShortText && NodeOps.isNumberLike(node);
                if (isShortText) {
                    ++nst;
                    if (isNumberLike) {
                        ++nnm;
                    }

                    let ele = NodeOps.bestElement(node);
                    if (ele != null && !init && !ele.hasAttribute("tp")) {
                        // not set at initialization, it's lazy loaded.
                        // "lz" is short for lazy.
                        // TODO: embed all pulsar generated data into a single attribute to reduce the page size
                        ele.setAttribute("lz", "1")
                    }

                    if (ele != null) {
                        let type = isNumberLike ? "nm" : "st";
                        // "tp" is short for type.
                        ele.setAttribute("tp", type);
                    }
                }
            }

            // Requirement: width/height are the maxima across *all* elements on the page.
            // Use scroll sizes to reflect the full layout; fall back to offset/client.
            // Add sanity checks to avoid skew from accidental huge/Infinity/NaN values.
            if (node && node.nodeType === 1) {
                let w;
                let h;

                try {
                    w = Math.max(node.scrollWidth || 0, node.offsetWidth || 0, node.clientWidth || 0);
                    h = Math.max(node.scrollHeight || 0, node.offsetHeight || 0, node.clientHeight || 0);
                } catch (e) {
                    w = 0;
                    h = 0;
                }

                if (!Number.isFinite(w) || w < 0) w = 0;
                if (!Number.isFinite(h) || h < 0) h = 0;

                // cap extreme values
                if (w > maxWidth) w = maxWidth;
                if (h > maxHeight) h = maxHeight;

                if (w > width) {
                    width = w;
                }
                if (h > height) {
                    height = h;
                }
            }
        });

        // Fallback: ensure at least the document's own sizes are considered.
        try {
            const de = document.documentElement;
            if (de) {
                let dw = Math.max(de.scrollWidth || 0, de.clientWidth || 0);
                let dh = Math.max(de.scrollHeight || 0, de.clientHeight || 0);
                if (!Number.isFinite(dw) || dw < 0) dw = 0;
                if (!Number.isFinite(dh) || dh < 0) dh = 0;
                if (dw > maxWidth) dw = maxWidth;
                if (dh > maxHeight) dh = maxHeight;
                width = Math.max(width, dw);
                height = Math.max(height, dh);
            }
            if (document.body) {
                let bw = Math.max(document.body.scrollWidth || 0, document.body.clientWidth || 0);
                let bh = Math.max(document.body.scrollHeight || 0, document.body.clientHeight || 0);
                if (!Number.isFinite(bw) || bw < 0) bw = 0;
                if (!Number.isFinite(bh) || bh < 0) bh = 0;
                if (bw > maxWidth) bw = maxWidth;
                if (bh > maxHeight) bh = maxHeight;
                width = Math.max(width, bw);
                height = Math.max(height, bh);
            }
        } catch (e) {
            // ignore
        }
    }

    // unexpected but occurs when do performance test to parallel harvest Websites
    if (!__pulsar_utils__.data) {
        return
    }

    let trace = __pulsar_utils__.data.trace;
    let initStat = trace.initStat;
    if (!initStat) {
        initStat = { w: width, h: height, na: na, ni: ni, nst: nst, nnm: nnm };
        trace.initStat = initStat
    }
    let lastStat = trace.lastStat;
    let lastStatus = trace.status;
    let state = document.readyState.substr(0, 1);
    let newMultiStatus = {
        status: {n: lastStatus.n, scroll: lastStatus.scroll, idl: lastStatus.idl, st: state, r: lastStatus.r},
        lastStat: {w: width, h: height, na: na, ni: ni, nst: nst, nnm: nnm},
        // changes from last round
        lastD: {
            w: width - lastStat.w,
            h: height - lastStat.h,
            na: na - lastStat.na,
            ni: ni - lastStat.ni,
            nst: nst - lastStat.nst,
            nnm: nnm - lastStat.nnm
        },
        // changes from the initialization
        initD: {
            w: width - initStat.w,
            h: height - initStat.h,
            na: na - initStat.na,
            ni: ni - initStat.ni,
            nst: nst - initStat.nst,
            nnm: nnm - initStat.nnm
        }
    };

    __pulsar_utils__.data.trace = Object.assign(trace, newMultiStatus)

    return __pulsar_utils__.data
};

/**
 * @param {Number} ratio The ratio of the page's height to scroll to, default is 0.5
 * */
__pulsar_utils__.scrollToMiddle = function(ratio = 0.5) {
    if (!document || !document.documentElement || !document.body) {
        return
    }

    if (ratio < 0 || ratio > 1) {
        ratio = 0.5
    }

    let x = 0;
    let y = Math.max(
        document.documentElement.scrollHeight,
        document.documentElement.clientHeight,
        document.body.scrollHeight
    );
    y = Math.min(y, 15000) * ratio

    window.scrollTo(x, y)
};

