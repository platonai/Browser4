/**
 * 检查一个元素是否处于“选中”状态。
 * 支持：
 *  - 原生 <input type="checkbox|radio">
 *  - 自定义控件 (role="checkbox|radio" + aria-checked)
 *
 * @param {Element} element 要检查的 DOM 元素
 * @param {boolean} [strict=true] 是否严格模式（默认为 true）
 * @returns {boolean|string} true / false / "mixed"
 */
__pulsar_utils__.isElementChecked = function(element, strict = true) {
    if (!element) {
        if (strict) throw this.createStacklessError('Element is null or undefined');
        return false;
    }

    // 1️⃣ 处理 ARIA 自定义控件
    const role = element.getAttribute('role');
    if (role && ['checkbox', 'radio'].includes(role.toLowerCase())) {
        const state = element.getAttribute('aria-checked');
        if (state === 'mixed') return 'mixed';
        return state === 'true';
    }

    // 2️⃣ 处理原生控件
    if (element instanceof HTMLInputElement &&
        ['checkbox', 'radio'].includes(element.type.toLowerCase())) {
        return element.checked;
    }

    // 3️⃣ 其他情况
    if (strict) {
        throw this.createStacklessError('Not a checkbox or radio button');
    } else {
        return false;
    }
};

/**
 * Scroll into view.
 *
 * @param {String} selector The element to scroll to
 * @param {Object} [options] Optional scroll options to override defaults
 * @deprecated use BrowserProtocol instead
 * */
__pulsar_utils__.scrollIntoView = function(selector, options) {
    try {
        const el = document.querySelector(selector);
        if (!el) return false;

        // Determine if scrolling is actually needed
        const rect = el.getBoundingClientRect();
        const vw = window.innerWidth || document.documentElement.clientWidth;
        const vh = window.innerHeight || document.documentElement.clientHeight;
        const fullyInView = rect.top >= 0 && rect.left >= 0 && rect.bottom <= vh && rect.right <= vw;

        if (!fullyInView) {
            const opts = Object.assign({
                behavior: 'smooth',
                block: 'center',
                inline: 'nearest'
            }, options || {});
            el.scrollIntoView(opts);
            return true;
        }
        return false;
    } catch (e) {
        // Fallback: best-effort immediate scroll to avoid breaking flows
        try {
            const el = document.querySelector(selector);
            if (el) {
                el.scrollIntoView({ behavior: 'auto', block: 'start', inline: 'nearest' });
                return true;
            }
        } catch (_) { /* ignore */ }
        return false;
    }
};

